// categories คืนรายชื่อหมวดทั้งหมด (สำหรับให้ frontend แสดงตัวเลือก)
func categories() []string {
	out := make([]string, 0, len(wordBank))
	for k := range wordBank {
		out = append(out, k)
	}
	return out
}

// pickRandomWord สุ่มคำจากหมวดที่ระบุ ถ้า category ว่างหรือไม่พบ จะสุ่มจากทุกหมวด
func pickRandomWord(category string) string {
	if list, ok := wordBank[category]; ok && len(list) > 0 {
		return list[rand.Intn(len(list))]
	}
	all := make([]string, 0)
	for _, list := range wordBank {
		all = append(all, list...)
	}
	if len(all) == 0 {
		return ""
	}
	return all[rand.Intn(len(all))]
}
